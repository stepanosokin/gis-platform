CREATE TABLE h3_data.observations (
  feature_id text PRIMARY KEY CHECK (feature_id <> ''),
  h3_id text NOT NULL REFERENCES h3_data.cells (h3_id),
  observed_at timestamptz NOT NULL,
  measurement integer
);
